import type { Layout } from "#layout";
import type { Profile } from "#profile";
import { GitConfigAbstract, type GitConfigType } from "./abstract.ts";

class GitConfig extends GitConfigAbstract {
    public static override render(input: GitConfigType): {
        main: string;
        profiles: { profile: string; content: string }[];
    } {
        const { profiles, layout } = input;
        const sections = profiles.map((profile) =>
            [
                // gitdir with a trailing slash matches every repository below the folder: where a repository lives
                // decides its account, whatever its remote URL looks like and however many remotes it has.
                `[includeIf ${GitConfig.quote(`gitdir:${layout.getProfilePath(profile.getName(), "repositories")}/`)}]`,
                `\tpath = ${GitConfig.quote(layout.getProfileConfigPath(profile.getName()))}`,
            ].join("\n")
        );
        return {
            main: [GitConfig.header(layout), sections.join("\n"), ""].join("\n"),
            profiles: profiles.map((profile) => ({
                profile: profile.getName(),
                content: GitConfig.renderProfile(profile, layout),
            })),
        };
    }

    public static override allowedSignersPath(layout: Layout, profile: string): string {
        return layout.getSshPath(profile, "allowed_signers");
    }

    public static override allowedSigner(email: string, publicKey: string): string {
        return `${email} ${publicKey.trim()}\n`;
    }

    public static override sshCommand(key: string, knownHosts: string): string {
        return [
            "ssh",
            "-i",
            GitConfig.shellQuote(key),
            // Only this key. Without it ssh also offers the keys of an agent, the server accepts the first one it
            // knows, and the push goes out as whichever account that key belongs to.
            "-o",
            "IdentitiesOnly=yes",
            // The profiles' own known_hosts, under local/: ~/.ssh in this container is secrets/ssh, the keys of
            // git-profiles' own repository, and the profiles stay out of it.
            "-o",
            `UserKnownHostsFile=${GitConfig.shellQuote(knownHosts)}`,
            "-o",
            "StrictHostKeyChecking=accept-new",
        ].join(" ");
    }

    public static override quote(value: string): string {
        return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
    }

    /**
     * A word for the shell git runs `core.sshCommand` with, in single quotes.
     * @param value - a path
     */
    protected static shellQuote(value: string): string {
        return `'${value.replaceAll("'", "'\\''")}'`;
    }

    /**
     * The two comment lines on top of every generated file.
     * @param layout - where the profiles are, named in the comment
     */
    protected static header(layout: Layout): string {
        return [
            `# Generated by git-profiles from ${layout.getProfilesDir()}.`,
            "# Edit the profiles and run `apply` again: this file is rewritten every time.",
            "",
        ].join("\n");
    }

    /**
     * The git config of one profile's repositories.
     * @param profile - the profile
     * @param layout - where its key files are
     */
    protected static renderProfile(profile: Profile, layout: Layout): string {
        const name = profile.getName();
        const identity = profile.getIdentity();
        const signing = profile.getSigning();
        const lines = [
            GitConfig.header(layout),
            "[user]",
            `\tname = ${GitConfig.quote(identity.getName())}`,
            `\temail = ${GitConfig.quote(identity.getEmail())}`,
        ];
        if (signing !== undefined) {
            const key = signing.isFile() ? layout.getSshPath(name, signing.getKey()) : signing.getKey();
            lines.push(`\tsigningkey = ${GitConfig.quote(key)}`);
        }
        lines.push(
            "[core]",
            `\tsshCommand = ${GitConfig.quote(GitConfig.sshCommand(layout.getSshPath(name, profile.getKey()), layout.getKnownHostsPath()))}`
        );
        if (signing !== undefined) {
            lines.push("[gpg]", `\tformat = ${signing.getFormat()}`);
            if (signing.isFile()) {
                const signers = GitConfig.allowedSignersPath(layout, name);
                lines.push('[gpg "ssh"]', `\tallowedSignersFile = ${GitConfig.quote(signers)}`);
            }
            lines.push("[commit]", "\tgpgsign = true", "[tag]", "\tgpgsign = true");
        }
        return [...lines, ""].join("\n");
    }
}

export { GitConfig };
